import { expect, test } from '@playwright/test';
import { ageAccount, clearSheets, goTo, grant, register, skipRankUp, skipTips, watchErrors } from './helpers';

test('most recent is default and sort survives ticks, token visits, tabs and reload', async ({page}) => {
  const errors = watchErrors(page);
  const handle = await register(page,'lpsort');
  await grant(handle,60_000);
  await ageAccount(handle,3*24*720+10);
  await skipRankUp(page);
  await clearSheets(page);
  await skipTips(page);
  await goTo(page,'launchpad');
  await page.getByTestId('tab-create').click();
  const ticker = Array.from({length:4},()=>String.fromCharCode(65+Math.floor(Math.random()*26))).join('');
  await page.getByTestId('lp-name').fill(`Sort ${ticker}`);
  await page.getByTestId('lp-ticker').fill(ticker);
  await page.getByTestId('lp-tagline-tg2').click();
  await page.getByTestId('lp-launch').click();
  await expect(page.getByTestId('lp-launch-sent')).toBeVisible();
  await page.getByTestId('tab-new').click();
  const sort = page.getByTestId('lp-sort-new');
  await expect(sort).toHaveValue('created');
  await page.getByTestId(`lp-open-${ticker}`).click();
  await expect(page.getByTestId('lp-token-page')).toBeVisible();
  await page.getByTestId('lp-back').click();
  await expect(sort).toHaveValue('created');
  await sort.selectOption('vol');
  await page.waitForTimeout(2200); // at least two of the test world's real tick updates
  await expect(sort).toHaveValue('vol');
  await page.getByTestId(`lp-open-${ticker}`).click();
  await expect(page.getByTestId('lp-token-page')).toBeVisible();
  await page.getByTestId('lp-back').click();
  await expect(sort).toHaveValue('vol');
  await page.getByTestId('tab-trending').click();
  await expect(page.getByTestId('lp-sort-trending')).toHaveValue('vol');
  await page.getByTestId('tab-new').click();
  await expect(sort).toHaveValue('vol');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-game','ready');
  await clearSheets(page);
  await goTo(page,'launchpad');
  await expect(sort).toHaveValue('vol');
  await sort.selectOption('created');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-game','ready');
  await clearSheets(page);
  await goTo(page,'launchpad');
  await expect(sort).toHaveValue('created');
  expect(errors).toEqual([]);
});
