// Regenerates src/catalog-data.ts from ledger-ref catalog.csv v2 + aliases.csv (PR #3 review F5).
// Usage: node scripts/gen-catalog.mjs [/workspace/specs/ledger-ref]
import { readFileSync, writeFileSync } from 'node:fs';

const dir = process.argv[2] ?? '/workspace/specs/ledger-ref';
const TEMPLATES = ['PAY', 'SWAP_ASSET', 'MINT', 'BURN', 'ELASTIC_IN', 'ELASTIC_OUT', 'LEND', 'REPAY', 'CB_CREDIT', 'CB_CREDIT_UNWIND', 'ACCRUE', 'ACCRUE_PAIR', 'FX', 'MOVE_QTY', 'RECLASS', 'ESCROW_PLACE', 'ESCROW_SETTLE', 'CONTROL_RECLASS'];

function parseCsv(text) {
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}
const leg = (s) => (/^\d{4}$/.test(s) ? Number(s) : s === '-' ? null : s); // '@ASSET' / '@' kept as markers
const lit = (v) => (v === null ? 'null' : typeof v === 'number' ? String(v) : `'${v}'`);

const cat = parseCsv(readFileSync(`${dir}/catalog.csv`, 'utf8'));
const ali = parseCsv(readFileSync(`${dir}/aliases.csv`, 'utf8'));
// PD-12 / errata E-4: a deprecated alias keeps no catalog row of its own (else ALIAS_SHADOWS_CODE); its target row inherits it.
const aliasNames = new Set(ali.map((a) => a.alias));
const dropped = cat.filter((r) => aliasNames.has(r.code)).map((r) => r.code);
const out = [
  '// GENERATED by scripts/gen-catalog.mjs from /workspace/specs/ledger-ref/catalog.csv v2 + aliases.csv. Do not edit by hand.',
  '// Columns per T03-02 legend (cards/03/T03-02.md:80-91). legA/legB: account code, \'@ASSET\'/\'@\' = caller passes it, null = not used.',
  "// Rows with `derived` set (8) carry class defaults from Systems, not a card row: TODO(systems).",
  "import type { CatalogSeedRow } from './catalog';",
  'export const CATALOG_SEED: readonly CatalogSeedRow[] = [',
];
for (const r of cat.filter((x) => !aliasNames.has(x.code))) {
  const tpl = r.allowedTemplates.split(/[\s;,()]+/).filter((t) => TEMPLATES.includes(t));
  const req = r.requestableBy === '-' ? '[]' : r.requestableBy === 'ALL' ? "'ALL'" : `[${r.requestableBy.split(',').map(Number).join(', ')}]`;
  const sec = r.sector === '-' ? '[]' : `[${r.sector.split(',').map((s) => `'${s}'`).join(', ')}]`;
  const opt = (k, v) => (v === '-' || v === '' ? '' : `, ${k}: '${v}'`);
  out.push(`  { code: '${r.code}', cls: '${r.class}', owner: ${Number(r.owner)}, cf: '${r.cf}', tpl: [${tpl.map((t) => `'${t}'`).join(', ')}], legA: ${lit(leg(r.legA))}, legB: ${lit(leg(r.legB))}, ` +
    `sectors: ${sec}, restrictedOk: ${r.restrictedOk === 'Y'}, requestableBy: ${req}, illicit: ${r.illicit === 'Y'}${opt('taxTag', r.taxTag)}${opt('family', r.family)}${r.derived ? ', derived: true' : ''} },`);
}
out.push('];', '', '/** aliases.csv (26 rows of 24 §8 + 2 of PD-12): alias -> canonical code(s). Posting an alias is invalid (INV-LED-002). */',
  'export const ALIAS_SEED: readonly (readonly [alias: string, targets: readonly string[]])[] = [');
for (const a of ali) out.push(`  ['${a.alias}', [${a.targets.split(/\s+/).filter(Boolean).map((t) => `'${t}'`).join(', ')}]],`);
out.push('];', '');
writeFileSync(new URL('../src/catalog-data.ts', import.meta.url), out.join('\n'));
console.log(`catalog rows ${cat.length - dropped.length} (dropped alias rows: ${dropped.join(', ')}), aliases ${ali.length}`);

// legpolicy.csv (Systems, E-11; signed off) -> src/legpolicy-data.ts. Allowed sets are parsed into a closed structure.
const lp = parseCsv(readFileSync(`${dir}/legpolicy.csv`, 'utf8'));
const allowed = (s) => {
  if (s === '-' || s === '') return '{ nums: [] }';
  const nums = []; const f = [];
  const asset = /ASSET_ACCT\(|@ASSET/.test(s); if (asset) f.push('asset: true');
  if (/NONMONEY_SAME_ENTITY/.test(s)) f.push('nonMoney: true');
  if (/^P&L/.test(s)) f.push('pnl: true');
  for (const t of s.replace(/ASSET_ACCT\([^)]*\)/, '').replace(/\(incl\.[^)]*\)/, '').split('|')) if (/^\s*\d{4}\s*$/.test(t)) nums.push(Number(t));
  return `{ nums: [${nums.join(', ')}]${f.map((x) => `, ${x}`).join('')} }`;
};
const lo = ['// GENERATED by scripts/gen-catalog.mjs from /workspace/specs/ledger-ref/legpolicy.csv (E-11, signed off). Do not edit by hand.',
  "import type { LegPolicyRow } from './legpolicy';", 'export const LEGPOLICY_SEED: readonly LegPolicyRow[] = ['];
for (const r of lp) {
  const side = (x) => `{ policy: '${r[`leg${x}_policy`]}', def: ${lit(leg(r[`leg${x}_default`]))}, allowed: ${allowed(r[`leg${x}_allowed`])} }`;
  lo.push(`  { code: '${r.code}', A: ${side('A')}, B: ${side('B')}, negSwap: ${r.negative_swap === 'Y'} },`);
}
lo.push('];', '');
writeFileSync(new URL('../src/legpolicy-data.ts', import.meta.url), lo.join('\n'));
console.log(`legpolicy rows ${lp.length}`);
