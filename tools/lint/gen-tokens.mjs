// Generates src/styles/tokens.ts from src/styles/tokens.css (Spec 1 §7.4). Run: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../../src/styles/tokens.css", import.meta.url), "utf8");
const PALETTES = ["ink-brass", "broadsheet", "phosphor", "riviera"];

function blockFor(selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`missing block ${selector}`);
  const body = css.slice(css.indexOf("{", start) + 1, css.indexOf("}", start));
  const vars = {};
  for (const m of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) vars[m[1]] = m[2].trim();
  return vars;
}

const root = blockFor(":root {");
const palettes = {};
for (const p of PALETTES) {
  const v = blockFor(`html[data-palette="${p}"]`);
  delete v["color-scheme"];
  palettes[p] = v;
}
const scheme = Object.fromEntries(PALETTES.map((p) => [p, /color-scheme:\s*(\w+)/.exec(css.slice(css.indexOf(`html[data-palette="${p}"]`)))[1]]));
const ms = (k) => Number(root[k].replace("ms", ""));
const motion = {
  fast: ms("dur-fast"), base: ms("dur-base"), slow: ms("dur-slow"), ambient: ms("dur-ambient"), tick: ms("dur-tick"),
  easeOut: root["ease-out"], easeInOut: root["ease-in-out"],
};

// Every other block that sets custom properties (17A T1-01: tokens.ts mirrors every var).
const MODES = {
  colorBlind: 'html[data-cb="1"] {',
  colorBlindBroadsheet: 'html[data-cb="1"][data-palette="broadsheet"] {',
  highContrast: 'html[data-hc="1"]',
  shadow: '[data-subpalette="shadow"] {',
  reducedMotion: 'html[data-motion="reduce"] {',
  reducedTransparency: 'html[data-transparency="reduce"] {',
};
const modes = Object.fromEntries(Object.entries(MODES).map(([k, sel]) => [k, blockFor(sel)]));
const modeSelectors = Object.fromEntries(Object.entries(MODES).map(([k, sel]) => [k, sel.replace(/ \{$/, "")]));

const out = `// GENERATED by tools/lint/gen-tokens.mjs from src/styles/tokens.css. Do not edit.
export type PaletteId = ${PALETTES.map((p) => `"${p}"`).join(" | ")};
export const PALETTE_IDS: readonly PaletteId[] = ${JSON.stringify(PALETTES)};
export const PALETTES: Record<PaletteId, Record<string, string>> = ${JSON.stringify(palettes, null, 2)};
export const COLOR_SCHEME: Record<PaletteId, "dark" | "light"> = ${JSON.stringify(scheme)};
export const MOTION = ${JSON.stringify(motion, null, 2)} as const;
/** Every custom property on :root, by name without the leading dashes. */
export const ROOT_TOKENS = ${JSON.stringify(root, null, 2)} as const;
export type RootToken = keyof typeof ROOT_TOKENS;
/** Overrides applied by html/data-* modes (colour-blind, high contrast, Shadow, reduced motion/transparency). */
export const MODE_TOKENS = ${JSON.stringify(modes, null, 2)} as const;
export const MODE_SELECTORS = ${JSON.stringify(modeSelectors, null, 2)} as const;
`;
writeFileSync(new URL("../../src/styles/tokens.ts", import.meta.url), out);
console.log("tokens.ts written");
