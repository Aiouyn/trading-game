#!/usr/bin/env python3
"""Compute a valid build order of all tasks and write BUILD-ORDER.md.
Constraints: (1) every task after the tasks in its depends_on; (2) every task of unit U after all tasks
of the units U hard-depends on (19 §12.2), except edges listed in SOFT (data that may land early).
Ties are broken by stage, then unit order, then task id. Reports unknown deps and cycles.
"""
import os, sys, re, heapq, collections
sys.path.insert(0, os.path.dirname(__file__))
import assemble, spec

UNIT_DEPS = {
 '19A': [], '23': ['19A'], '22A': ['19A'], '20A': ['19A'], '02': ['19A', '23', '22A', '20A'], '03': ['02'],
 '19B': ['02', '03'], '14A': ['03'], '13A': ['03', '14A'], '15A': ['03', '14A', '19B'], '19C': ['19B', '14A'],
 '17A': ['19C'], '04': ['03'], '16A': ['04'], '05': ['03', '04', '14A', '13A'], '06A': ['05'],
 '07A': ['03', '04', '06A'], '07B': ['07A', '06A'], '06B': ['07B'], '06C': ['06A', '07A'],
 '10A': ['03', '04', '22A'], '10B': ['10A', '07A'], '09A': ['10A', '03', '04'], '09B': ['09A', '06A', '07A', '15A'],
 '08': ['06B', '07B', '09A', '10B'], '11': ['05', '06A', '14A', '19B'], '12': ['11', '09A', '10A', '13A'],
 '13B': ['12', '05', '07B', '08', '13A', '15A'], '16B': ['16A', '08', '09B', '10B'], '16C': ['16B', '13B'],
 '14B': ['14A', '10B', '13B'], '15B': ['15A', '14B', '16A', '19C'], '17B': ['17A'],
 '18': ['17B', '05', '09A', '14A', '16A'], '19D': ['19C', '11', '15B'], '21': ['19C', '15B', '14B'],
 '22B': ['22A'], '20B': [],
}
STAGE_OF = {}
for st, units in [('S0', ['19A', '23', '22A', '20A', '02', '03']), ('S1', ['19B', '14A', '04', '13A', '15A', '16A', '19C', '17A']),
                  ('S2', ['05', '06A', '07A', '07B', '06B', '06C']), ('S3', ['10A', '09A', '10B', '09B']), ('S4', ['08']),
                  ('S5', ['11', '12', '13B']), ('S6', ['16B', '16C']), ('S7', ['14B', '15B']), ('S8', ['17B', '18', '22B']),
                  ('S9', ['21', '19D']), ('S10', ['20B'])]:
    for u in units: STAGE_OF[u] = st
UNIT_RANK = {u: i for i, u in enumerate([u for st in sorted(set(STAGE_OF.values()), key=lambda s: int(s[1:])) for u in STAGE_OF if STAGE_OF[u] == st])}
UNIT_DEPS['20B'] = [u for u in UNIT_DEPS if u != '20B']

def unit_of(c): return str(c.get('unit')).replace('.', '')

def main():
    cards = assemble.all_cards()
    by_unit = collections.defaultdict(list)
    for cid, c in cards.items(): by_unit[unit_of(c)].append(cid)
    preds = collections.defaultdict(set); problems = []
    for cid, c in cards.items():
        for d in c.get('depends_on') or []:
            if d in cards: preds[cid].add(d)
            else: problems.append(f'{cid}: unknown dependency {d}')
        u = unit_of(c)
        if u not in UNIT_DEPS: problems.append(f'{cid}: unknown unit {u}')
        # unit-level edges: 17B and 22B tasks follow their task-level deps only (they interleave)
        if u in ('17B', '22B'): continue
        for du in UNIT_DEPS.get(u, []):
            if du in ('17B', '22B'): continue
            for p in by_unit.get(du, []): preds[cid].add(p)
    # Kahn with priority
    indeg = {cid: len(preds[cid]) for cid in cards}
    succ = collections.defaultdict(set)
    for cid, ps in preds.items():
        for p in ps: succ[p].add(cid)
    def key(cid):
        u = unit_of(cards[cid]); return (int(STAGE_OF.get(u, 'S99')[1:]), UNIT_RANK.get(u, 999), cid)
    heap = [key(c) for c in cards if indeg[c] == 0]; heapq.heapify(heap); order = []
    while heap:
        _, _, cid = heapq.heappop(heap); order.append(cid)
        for s in sorted(succ[cid]):
            indeg[s] -= 1
            if indeg[s] == 0: heapq.heappush(heap, key(s))
    if len(order) < len(cards):
        stuck = sorted(set(cards) - set(order))
        problems.append('CYCLE among: ' + ', '.join(stuck[:40]))
        order += stuck
    sizes = {}
    for cid in order:
        try: _, sizes[cid], _, _ = assemble.build_pack(cards[cid], cards)
        except Exception as e: sizes[cid] = -1
    lines = ['# Build order (generated by tools/order.py; do not edit by hand except the checkboxes)', '',
             f'{len(order)} tasks. Work top to bottom. A task may start when every task in its "after" column is done. Pack = packs/<unit>/<id>.md.', '',
             '| # | done | task | stage | unit | title | after (direct deps) | pack tokens | est. LOC |', '|---|---|---|---|---|---|---|---|---|']
    for i, cid in enumerate(order, 1):
        c = cards[cid]; u = unit_of(c)
        deps = ', '.join(c.get('depends_on') or []) or '–'
        lines.append(f"| {i} | [ ] | {cid} | {STAGE_OF.get(u,'?')} | {u} | {str(c.get('title','')).replace('|','/')} | {deps} | {sizes[cid]} | {c.get('est_loc','')} |")
    if problems:
        lines += ['', '## Problems found', ''] + ['- ' + p for p in problems]
    open(os.path.join(assemble.ROOT, 'BUILD-ORDER.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{len(order)} tasks ordered; {len(problems)} problems')
    for p in problems[:50]: print(' ', p)

if __name__ == '__main__':
    main()
